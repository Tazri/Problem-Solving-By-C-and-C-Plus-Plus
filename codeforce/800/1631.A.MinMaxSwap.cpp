void _DIBBA()
{
    int n;
    cin >> n;
    vector<int> a(n);
    vector<int> b(n);

    for (int i = 0; i < n; i++)
    {
        cin >> a[i];
    }

    for (int i = 0; i < n; i++)
    {
        cin >> b[i];
    }

    for (int i = 0; i < n; i++)
    {
        int mn = min(a[i], b[i]);
        int mx = max(a[i], b[i]);
        a[i] = mx;
        b[i] = mn;
    }

    int mx1 = *max_element(a.begin(), a.end());
    int mx2 = *max_element(b.begin(), b.end());

    cout << mx1 * mx2 << endl;
}

